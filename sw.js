// ФОНОВЫЕ PUSH-УВЕДОМЛЕНИЯ (приложение закрыто)
// Платформа: Cloud Function onBroadcastCreated/onAlertCreated
// отправляет Web Push (VAPID) с JSON {title,body,tag,url}.
