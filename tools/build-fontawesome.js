#!/usr/bin/env node
'use strict';
/*
 * build-fontawesome.js — самодостаточный сабсет Font Awesome (аудит 2026-10, п.9).
 *
 * Было: каждая из 16 страниц тянула с cdnjs `font-awesome/6.5.0/css/all.min.css`
 * (~100 КБ) + при первом обращении woff2 на ~1650 глифов — ради ~200 иконок.
 * Это сторонняя рантайм-зависимость: нет сети или CDN не попал в SWR-кэш —
 * интерфейс без иконок.
 *
 * Стало: из установленного npm-пакета @fortawesome/fontawesome-free@6.5.0
 * (тот же релиз, что отдавал cdnjs) берём метаданные и webfonts, вырезаем
 * только используемые в проекте глифы и пишем:
 *   fonts/fa-<стиль>-<вес>-subset-<hash8>.woff2
 *   css/fontawesome-subset.css
 * Имя файла шрифта содержит хеш содержимого, поэтому immutable-кэширование
 * безопасно: изменился сабсет — изменился URL.
 *
 * Побочная, но главная находка: скрипт — ещё и гейт. Пять имён иконок в коде
 * (`fa-swords`, `fa-users-plus`, `fa-users-rotate`, `fa-wifi-slash`,
 * `fa-arrow-down-to-bracket`) в FA 6.5.0 НЕ существуют — они появились только в
 * FA 7.x. Пока шрифт грузился с CDN, это выглядело как «иконка не нарисовалась»
 * и годами никого не тревожило. Теперь неизвестное имя — ошибка сборки, а не
 * молчаливый пустой прямоугольник.
 *
 * Режимы:
 *   node tools/build-fontawesome.js          — пересобрать (перезаписать файлы)
 *   node tools/build-fontawesome.js --check  — только проверить актуальность (CI)
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const CHECK = process.argv.includes('--check');
const QUIET = process.argv.includes('--quiet');

const FA_PKG = 'node_modules/@fortawesome/fontawesome-free';
const OUT_CSS = 'css/fontawesome-subset.css';
const OUT_FONT_DIR = 'fonts';

const BEGIN = '/* BEGIN FONTAWESOME SUBSET (auto-generated by tools/build-fontawesome.js — не править вручную; запуск: npm run build:fonts) */';
const END = '/* END FONTAWESOME SUBSET */';

// Семейства, которые реально используются (fas / far / fab). Pro-стили
// (light/thin/duotone) в бесплатном пакете отсутствуют — их появление в коде
// должно стать ошибкой, а не сюрпризом в проде.
const FAMILIES = [
    { style: 'solid', weight: 900, ttf: 'fa-solid-900.ttf', slug: 'fa-solid-900' },
    { style: 'regular', weight: 400, ttf: 'fa-regular-400.ttf', slug: 'fa-regular-400' },
    { style: 'brands', weight: 400, ttf: 'fa-brands-400.ttf', slug: 'fa-brands-400' }
];

// Утилиты FA, не являющиеся иконками. Кладём ровно те, что встречаются в коде:
// сабсет должен отдавать только используемое.
const UTILITIES = {
    'fa-spin': [
        '.fa-spin {',
        '    animation-name: fa-spin;',
        '    animation-duration: 2s;',
        '    animation-iteration-count: infinite;',
        '    animation-timing-function: linear;',
        '}',
        '@keyframes fa-spin {',
        '    0% { transform: rotate(0deg); }',
        '    100% { transform: rotate(360deg); }',
        '}',
        '@media (prefers-reduced-motion: reduce) {',
        '    .fa-spin { animation-duration: 0.01ms; animation-iteration-count: 1; }',
        '}'
    ].join('\n')
};

// Классы семейств — не иконки и не утилиты, в сабсете учитываются отдельно
// (определяют, какой @font-face применится).
const FAMILY_CLASSES = new Set([
    'fa-solid', 'fa-regular', 'fa-brands', 'fa-light', 'fa-thin', 'fa-duotone', 'fa-sharp'
]);

function fail(msg) {
    console.error('build-fontawesome: ' + msg);
    process.exit(1);
}
function sha8(buf) {
    return crypto.createHash('sha1').update(buf).digest('hex').slice(0, 8);
}
function abs(p) { return path.join(ROOT, p); }

// ── 1. Метаданные FA ──────────────────────────────────────────────────────
const metaPath = abs(FA_PKG + '/metadata/icon-families.json');
if (!fs.existsSync(metaPath)) {
    fail('не найден ' + FA_PKG + ' — выполните `npm ci`.');
}
const META = JSON.parse(fs.readFileSync(metaPath, 'utf8'));
const FA_VERSION = JSON.parse(fs.readFileSync(abs(FA_PKG + '/package.json'), 'utf8')).version;

// Псевдонимы: в FA6 часть имён — ссылки на канонические
// (например `golf-ball` → `golf-ball-tee`). Класс в разметке может быть любым.
const ALIAS_TO_CANONICAL = new Map();
for (const name of Object.keys(META)) {
    const aliases = (META[name].aliases && META[name].aliases.names) || [];
    for (const a of aliases) ALIAS_TO_CANONICAL.set(a, name);
}

function freeStyles(name) {
    const lic = META[name].familyStylesByLicense || {};
    return (lic.free || []).map(s => s.style);
}

// ── 2. Корпус: где искать классы ──────────────────────────────────────────
const corpus = [];
for (const f of fs.readdirSync(ROOT)) {
    if (f.endsWith('.html')) corpus.push(f);
}
for (const dir of ['js', 'css', 'src']) {
    const walk = (d) => {
        if (!fs.existsSync(abs(d))) return;
        for (const e of fs.readdirSync(abs(d), { withFileTypes: true })) {
            const rel = d + '/' + e.name;
            if (e.isDirectory()) walk(rel);
            else if (/\.(js|css|html)$/.test(e.name)) corpus.push(rel);
        }
    };
    walk(dir);
}
// Собственный вывод в корпус не входит — иначе сабсет不肯 сузиться и будет
// расти сам от себя.
const scanFiles = corpus.filter(f => f !== OUT_CSS).sort();

// ── 3. Сбор классов fa-* с привязкой к месту ──────────────────────────────
const TOKEN_RE = /\bfa-[a-z0-9-]+/g;
const found = new Map(); // 'fa-trophy' -> Set('file:line')

for (const file of scanFiles) {
    const lines = fs.readFileSync(abs(file), 'utf8').split('\n');
    lines.forEach(function (line, i) {
        let m;
        TOKEN_RE.lastIndex = 0;
        while ((m = TOKEN_RE.exec(line)) !== null) {
            const tok = m[0];
            if (!found.has(tok)) found.set(tok, new Set());
            found.get(tok).add(file + ':' + (i + 1));
        }
    });
}

// ── 4. Разбор: иконки / утилиты / ошибки ──────────────────────────────────
const icons = new Map();   // каноническое имя -> { code, styles:Set, names:Set }
const utilities = new Set();
const problems = [];
const notes = [];

for (const tok of Array.from(found.keys()).sort()) {
    const where = Array.from(found.get(tok)).sort();
    const name = tok.slice(3);

    if (FAMILY_CLASSES.has(tok)) continue; // fas/far задаются короткими классами

    // «Висячий» префикс из динамической сборки имени: 'fa-chevron-' + (up|down).
    // Раскрываем во все иконки с этим префиксом — дешевле и надёжнее, чем
    // угадывать ветки условия.
    if (tok.endsWith('-')) {
        const prefix = name; // 'chevron-'
        const matched = Object.keys(META).filter(n => n.startsWith(prefix)).sort();
        if (!matched.length) {
            problems.push('префикс ' + tok + ' не соответствует ни одной иконке (' + where.join(', ') + ')');
            continue;
        }
        notes.push(tok + ' — динамический префикс, раскрыт в ' + matched.length +
            ' иконок: ' + matched.join(', ') + ' (' + where.join(', ') + ')');
        // В разметку подставляем уже конкретные имена: сам по себе `.fa-chevron-`
        // как селектор бессмысленен.
        for (const n of matched) addIcon(n, 'fa-' + n);
        continue;
    }

    if (UTILITIES[tok]) { utilities.add(tok); continue; }

    const canonical = META[name] ? name : ALIAS_TO_CANONICAL.get(name);
    if (!canonical) {
        problems.push('класс ' + tok + ' отсутствует в Font Awesome ' + FA_VERSION +
            ' (иконка нарисуется пустой): ' + where.join(', '));
        continue;
    }
    addIcon(canonical, tok);
}

function addIcon(canonical, token) {
    if (!icons.has(canonical)) {
        icons.set(canonical, {
            code: META[canonical].unicode,
            styles: new Set(),
            tokens: new Set()
        });
    }
    const rec = icons.get(canonical);
    rec.tokens.add(token);
    const styles = freeStyles(canonical).filter(s => FAMILIES.some(f => f.style === s));
    if (!styles.length) {
        problems.push('иконка ' + token + ' (каноническая ' + canonical + ') есть только в платных ' +
            'стилях Font Awesome Pro: ' + Array.from(found.get(token)).join(', '));
        return;
    }
    styles.forEach(s => rec.styles.add(s));
}

if (problems.length) {
    console.error('Font Awesome ' + FA_VERSION + ': проблемы в разметке (' + problems.length + '):');
    problems.forEach(p => console.error('  — ' + p));
    console.error('\nВарианты: заменить имя на существующее в FA ' + FA_VERSION +
        ' (список: node_modules/@fortawesome/fontawesome-free/metadata/icon-families.json)' +
        ' либо обновить версию пакета.');
    process.exit(1);
}

// ── 5. Подготовка наборов символов по семействам ──────────────────────────
const plan = FAMILIES.map(function (fam) {
    const names = Array.from(icons.keys())
        .filter(n => icons.get(n).styles.has(fam.style))
        .sort();
    const text = names.map(n => String.fromCodePoint(parseInt(icons.get(n).code, 16))).join('');
    return { fam, names, text };
});

// ── 6. Сабсетирование ─────────────────────────────────────────────────────
let subsetFont;
try {
    subsetFont = require('subset-font');
} catch (e) {
    fail('не установлен subset-font — выполните `npm ci`.');
}

async function build() {
    const written = [];
    for (const entry of plan) {
        if (!entry.names.length) { entry.out = null; continue; }
        const ttfPath = abs(FA_PKG + '/webfonts/' + entry.fam.ttf);
        if (!fs.existsSync(ttfPath)) fail('нет файла шрифта ' + entry.fam.ttf);
        const ttf = fs.readFileSync(ttfPath);
        const woff2 = await subsetFont(ttf, entry.text, { targetFormat: 'woff2' });
        if (!woff2 || woff2.length < 100) fail('сабсет ' + entry.fam.ttf + ' пуст или подозрителен');
        const hash = sha8(woff2);
        const file = OUT_FONT_DIR + '/' + entry.fam.slug + '-subset-' + hash + '.woff2';
        entry.out = { file, buf: woff2, hash };
        written.push(file);
    }
    return { written };
}

function renderCss(plan) {
    const lines = [];
    lines.push(BEGIN);
    lines.push('/*');
    lines.push(' * Подмножество Font Awesome ' + FA_VERSION + ': ' + icons.size + ' иконок из ' +
        Object.keys(META).length + ' в пакете.');
    lines.push(' * Собрано tools/build-fontawesome.js по классам fa-* в *.html, js/**, css/**, src/**.');
    lines.push(' * ВАЖНО: файл генерируется — ручные правки будут потеряны при `npm run build:fonts`.');
    lines.push(' */');
    lines.push('');

    // Шрифты. Имя файла несёт хеш содержимого: поменялся сабсет — поменялся URL,
    // и immutable-кэш клиента не отдаст старые глифы.
    for (const entry of plan) {
        if (!entry.out) continue;
        const family = entry.fam.style === 'brands' ? 'FA Subset Brands' : 'FA Subset';
        lines.push('@font-face {');
        lines.push('    font-family: "' + family + '";');
        lines.push('    font-style: normal;');
        lines.push('    font-weight: ' + entry.fam.weight + ';');
        lines.push('    font-display: block;');
        lines.push('    src: url("../' + entry.out.file + '") format("woff2");');
        lines.push('}');
    }
    lines.push('');

    // Базовые правила. Повторяем раскладку FA6: `.fa` сам по себе — solid.
    lines.push('.fa, .fas, .fa-solid {');
    lines.push('    font-family: "FA Subset";');
    lines.push('    font-weight: 900;');
    lines.push('}');
    lines.push('.far, .fa-regular {');
    lines.push('    font-family: "FA Subset";');
    lines.push('    font-weight: 400;');
    lines.push('}');
    lines.push('.fab, .fa-brands {');
    lines.push('    font-family: "FA Subset Brands";');
    lines.push('    font-weight: 400;');
    lines.push('}');
    lines.push('.fa, .fas, .far, .fab, .fa-solid, .fa-regular, .fa-brands {');
    lines.push('    -moz-osx-font-smoothing: grayscale;');
    lines.push('    -webkit-font-smoothing: antialiased;');
    lines.push('    display: var(--fa-display, inline-block);');
    lines.push('    font-style: normal;');
    lines.push('    font-variant: normal;');
    lines.push('    line-height: 1;');
    lines.push('    text-rendering: auto;');
    lines.push('}');
    // Иконка по умолчанию наследует размер шрифта (как в FA6 через em).
    lines.push('.fa, .fas, .far, .fab { font-size: inherit; }');
    lines.push('');

    for (const util of Array.from(utilities).sort()) {
        lines.push(UTILITIES[util]);
        lines.push('');
    }

    // По одному правилу на иконку: кодовые точки в FA одинаковы для всех
    // стилей одного имени, а гарнитуру задаёт класс семейства (.fas/.far/.fab).
    for (const name of Array.from(icons.keys()).sort()) {
        const rec = icons.get(name);
        // В разметке могут встречаться и каноническое имя, и псевдоним
        // (`golf-ball` → `golf-ball-tee`) — описываем оба селектора.
        // ::before нужен КАЖДОМУ селектору по отдельности: запись
        // `.fa-a, .fa-b::before` применится к `.fa-a` целиком, а не к его
        // псевдоэлементу, и вместо иконки получится пустой элемент.
        const selectors = Array.from(rec.tokens).sort().map(t => '.' + t + '::before').join(', ');
        lines.push(selectors + ' { content: "\\' + rec.code + '"; }');
    }

    lines.push('');
    lines.push(END);
    return lines.join('\n') + '\n';
}

build().then(function ({ written }) {
    const css = renderCss(plan);

    // ── 7. Запись ─────────────────────────────────────────────────────────
    const fontDir = abs(OUT_FONT_DIR);
    if (!CHECK && !fs.existsSync(fontDir)) fs.mkdirSync(fontDir, { recursive: true });

    // Удаляем устаревшие файлы сабсета: имена содержат хеш, поэтому старые
    // копии иначе копились бы в репозитории вечно.
    const keep = new Set(written);
    const stale = fs.existsSync(fontDir)
        ? fs.readdirSync(fontDir).filter(f => /^fa-.*-subset-[0-9a-f]{8}\.woff2$/.test(f) && !keep.has(OUT_FONT_DIR + '/' + f))
        : [];

    const cssPath = abs(OUT_CSS);
    const oldCss = fs.existsSync(cssPath) ? fs.readFileSync(cssPath, 'utf8') : null;

    if (CHECK) {
        const expectedFonts = written.filter(f => !fs.existsSync(abs(f)));
        if (expectedFonts.length || stale.length || oldCss !== css) {
            console.error('build-fontawesome --check: сабсет устарел.');
            if (oldCss !== css) console.error('  — ' + OUT_CSS + ' не соответствует корпусу');
            expectedFonts.forEach(f => console.error('  — отсутствует ' + f));
            stale.forEach(f => console.error('  — лишний файл ' + OUT_FONT_DIR + '/' + f));
            console.error('Запустите: npm run build:fonts');
            process.exit(1);
        }
        if (!QUIET) {
            console.log('build-fontawesome --check: OK. иконок: ' + icons.size +
                ', гарнитур: ' + written.length + ', CSS: ' + css.length + ' байт');
        }
        return;
    }

    for (const f of written) fs.writeFileSync(abs(f), plan.find(p => p.out && p.out.file === f).out.buf);
    for (const f of stale) fs.rmSync(path.join(fontDir, path.basename(f)), { force: true });
    fs.writeFileSync(cssPath, css);

    // ── 8. Отчёт ──────────────────────────────────────────────────────────
    const fullCss = fs.readFileSync(abs(FA_PKG + '/css/all.min.css'));
    const fullFonts = FAMILIES.reduce(function (acc, f) {
        const p = abs(FA_PKG + '/webfonts/' + f.slug + '.woff2');
        return acc + (fs.existsSync(p) ? fs.statSync(p).size : 0);
    }, 0);
    const subsetBytes = plan.reduce((acc, p) => acc + (p.out ? p.out.buf.length : 0), 0) + Buffer.byteLength(css);

    if (!QUIET) {
        notes.forEach(n => console.log('  · ' + n));
        console.log('Font Awesome ' + FA_VERSION + ': иконок в сабсете ' + icons.size +
            ' (в пакете ' + Object.keys(META).length + ')');
        plan.forEach(function (p) {
            console.log('  ' + p.fam.slug + ': ' + p.names.length + ' глифов' +
                (p.out ? ', ' + p.out.buf.length + ' байт' : ', не используется'));
        });
        console.log('  css/fontawesome-subset.css: ' + Buffer.byteLength(css) + ' байт' +
            (utilities.size ? ' (утилиты: ' + Array.from(utilities).join(', ') + ')' : ''));
        console.log('  итого ' + subsetBytes + ' байт против ' + (fullCss.length + fullFonts) +
            ' байт полного комплекта (' + Math.round((1 - subsetBytes / (fullCss.length + fullFonts)) * 100) + '% экономии)');
        if (stale.length) console.log('  удалено устаревших файлов: ' + stale.length);
    }
}).catch(function (e) {
    fail('сборка сабсета не удалась: ' + (e && e.message ? e.message : e));
});
