var fails = 0, total = 0;

function setMode(m) {
    NV.setMode(m);
    NV.setAutoApply(true);
    NV.setCustomAliases(m === 'C' ? CUSTOM_ALIASES : '');
}

function show(v) { return v === null ? 'нет' : v; }
function pad(s, n) { s = String(s); while (s.length < n) s += ' '; return s; }

console.log('=== Совпадение ФИО (js/name-variants.js → match) ===\n');
CASES.forEach(function(c) {
    var m = c[0], lf = c[1], ll = c[2], rf = c[3], rl = c[4], want = c[5], why = c[6];
    setMode(m);
    var got = NV.match(lf, ll, rf, rl, (lf + ' ' + ll).trim(), (rf + ' ' + rl).trim());
    total++;
    var ok = got === want;
    if (!ok) fails++;
    console.log((ok ? ' ok  ' : 'FAIL ') + ' | ' + pad(m, 3) + ' | «' + ll + ' ' + lf + '» vs «' + rl + ' ' + rf + '» → ' +
        pad(show(got), 6) + ' (ожид. ' + pad(show(want), 6) + ')  ' + why);
});

console.log('\n=== Запросы к базе АГР (queryVariants) ===\n');
QUERY_CASES.forEach(function(c) {
    var m = c[0], f = c[1], l = c[2], must = c[3];
    setMode(m);
    var got = NV.queryVariants(f, l);
    total++;
    var missing = must.filter(function(q) { return got.indexOf(q) === -1; });
    var ok = missing.length === 0;
    if (!ok) fails++;
    console.log((ok ? ' ok  ' : 'FAIL ') + ' | ' + pad(m, 3) + ' | «' + l + ' ' + f + '» → ' +
        JSON.stringify(got) + (ok ? '' : '  ← не хватает: ' + JSON.stringify(missing)));
});

