// Тесты импорта участников из Excel/таблиц (js/tn-mgr-core.js §9).
// Проверяем, что имя, фамилия и гандикап находятся по всем столбцам и
// ячейкам, служебные строки пропускаются, а все листы книги читаются.
// Запуск: node tools/test-tn-mgr-import.js (входит в npm test).
'use strict';

var C = require('../js/tn-mgr-core.js');

var failures = 0, total = 0;
function eq(actual, expected, label) {
    total++;
    if (JSON.stringify(actual) !== JSON.stringify(expected)) {
        failures++;
        console.error('FAIL', label, '\n  actual:  ', JSON.stringify(actual), '\n  expected:', JSON.stringify(expected));
    } else console.log('ok  -', label);
}
function fios(parsed) { return parsed.players.map(function (p) { return p.fio; }); }
function his(parsed) { return parsed.players.map(function (p) { return p.hi; }); }

// ----------------------------------------------------------
// 1. Заголовки: широкая матрица написаний
// ----------------------------------------------------------
eq(C.headerKind('ФИО'), 'fio', 'заголовок «ФИО»');
eq(C.headerKind('Ф.И.О.'), 'fio', 'заголовок «Ф.И.О.»');
eq(C.headerKind('Фамилия'), 'lastName', 'заголовок «Фамилия»');
eq(C.headerKind('Имя'), 'firstName', 'заголовок «Имя» (а не «ФИО»)');
eq(C.headerKind('Last Name'), 'lastName', 'заголовок «Last Name»');
eq(C.headerKind('First name'), 'firstName', 'заголовок «First name»');
eq(C.headerKind('Handicap Index'), 'hi', 'заголовок «Handicap Index»');
eq(C.headerKind('Гандикап'), 'hi', 'заголовок «Гандикап»');
eq(C.headerKind('ИГ'), 'hi', 'заголовок «ИГ» (точный гандикап)');
eq(C.headerKind('Игровой гандикап'), 'ch', 'заголовок «Игровой гандикап» (CH)');
eq(C.headerKind('ТИ'), 'tee', 'заголовок «ТИ»');
eq(C.headerKind('Пол'), 'gender', 'заголовок «Пол»');
eq(C.headerKind('Группа'), 'group', 'заголовок «Группа»');
eq(C.headerKind('№'), 'no', 'заголовок «№»');
eq(C.headerKind('Полина'), '', 'имя «Полина» не считается колонкой «Пол»');
eq(C.headerKind('Петров Пётр'), '', 'строка с ФИО — не заголовок');

// ----------------------------------------------------------
// 2. Раздельные колонки «Фамилия» и «Имя»
// ----------------------------------------------------------
var split = C.parseParticipants([
    ['Фамилия', 'Имя', 'Гандикап'],
    ['Иванов', 'Иван', '12,4'],
    ['Петрова', 'Мария', '']
]);
eq(fios(split), ['Иванов Иван', 'Петрова Мария'], 'имя и фамилия собираются из двух колонок');
eq(his(split), [12.4, null], 'гандикап из третьей колонки');
eq(split.players[0].lastName, 'Иванов', 'фамилия записана в lastName');
eq(split.players[0].firstName, 'Иван', 'имя записано в firstName');
eq(split.columns, { lastName: 0, firstName: 1, hi: 2 }, 'колонки определены по заголовкам');

var reversed = C.parseParticipants([
    ['Имя', 'Фамилия', 'HI'],
    ['Иван', 'Иванов', '9,1']
]);
eq(fios(reversed), ['Иванов Иван'], 'порядок колонок «Имя/Фамилия» тоже работает');
eq(his(reversed), [9.1], 'гандикап в колонке HI');

var english = C.parseParticipants([
    ['First Name', 'Last Name', 'Handicap Index'],
    ['Anna', 'Sidorova', '24.0'],
    ['Ivan', 'Petrov', 'bad']
]);
eq(fios(english), ['Sidorova Anna', 'Petrov Ivan'], 'английские заголовки имени и фамилии');
eq(english.issues.length, 1, 'нечитаемый гандикап попадает в issues');
eq(english.issues[0].code, 'bad-hcp', 'код проблемы — bad-hcp');

// ----------------------------------------------------------
// 3. Шапка отчёта над таблицей и служебные строки
// ----------------------------------------------------------
var titled = C.parseParticipants([
    ['Гольф-клуб «Пестово»'],
    ['Кубок клуба, 16.05.2026'],
    ['№', 'ФИО', 'Гандикап', 'Пол'],
    ['1', 'Иванов Иван', '12,4', 'муж'],
    ['2', 'Смирнова Наталия', '', 'жен'],
    ['', '', 'Итого', ''],
    ['', 'Гандикап', '', '']
]);
eq(fios(titled), ['Иванов Иван', 'Смирнова Наталия'], 'строки над шапкой и «Итого» пропускаются');
eq(titled.headerRow, 3, 'шапка найдена не в первой строке');
eq(titled.issues.length, 0, 'служебные строки не считаются ошибками');
eq(titled.players[1].gender, 'women', 'пол из строки участника');

// ----------------------------------------------------------
// 4. Одна колонка с ФИО; шапка «Игрок» + клуб + HI
// ----------------------------------------------------------
var single = C.parseParticipants([['Иванов Иван'], ['Петров Пётр']]);
eq(fios(single), ['Иванов Иван', 'Петров Пётр'], 'таблица без заголовков: одна колонка имён');
eq(his(single), [null, null], 'без гандикапа участники добавляются с пустым HI');

var club = C.parseParticipants([
    ['№', 'Игрок', 'Клуб', 'HI', 'CH'],
    ['1', 'Иванов Иван Иванович', 'Пестово', '10.5', '12'],
    ['2', 'O\'Brien Patrick', 'Гость', '8.6', '9']
]);
eq(fios(club), ['Иванов Иван Иванович', "O'Brien Patrick"], 'участники из колонки «Игрок»');
eq(his(club), [10.5, 8.6], 'HI и CH распознаны по заголовкам');
eq(club.players[0].ch, 12, 'игровой гандикап CH прочитан');
eq(club.players[0].club, 'Пестово', 'клуб из строки');

// ----------------------------------------------------------
// 5. Гандикап в любой колонке и в любом написании
// ----------------------------------------------------------
var anyColumn = C.parseParticipants([
    ['Иванов Иван', 'муж', '15'],
    ['Петров Пётр', 'муж', '20,7']
]);
eq(his(anyColumn), [15, 20.7], 'без заголовков гандикап находится в третьей колонке');
eq(anyColumn.players[0].gender, 'men', 'колонка «муж» определена как пол');

var formats = C.parseParticipants([
    ['ФИО', 'Гандикап'],
    ['Смит Джон', '+2,5'],
    ['Петров Пётр', 'HI 8.2'],
    ['Сидоров Семён', 'ИГ: 14'],
    ['Кузнецов Кирилл', '13.8 (HI)']
]);
eq(his(formats), [-2.5, 8.2, 14, 13.8], 'гандикап с «+», подписью HI/ИГ и в скобках');
eq(formats.issues.length, 0, 'распознанные гандикапы не дают ошибок');

var badHcp = C.parseParticipants([
    ['ФИО', 'Гандикап'],
    ['Иванов Иван', 'нет'],
    ['Петров Пётр', '12,4']
]);
eq(badHcp.issues.length, 1, '«нет» в колонке гандикапа — ошибка строки');
eq(his(badHcp), [null, 12.4], 'остальные участники прочитаны');

// ----------------------------------------------------------
// 6. Служебные строки не становятся участниками
// ----------------------------------------------------------
var junk = C.parseParticipants([
    ['ФИО', 'Гандикап'],
    ['Иванов Иван', '12'],
    ['Итого', '12'],
    ['Всего участников: 1', ''],
    ['1', '2'],
    ['ФИО', 'Гандикап'],
    ['Петров Пётр', '18']
]);
eq(fios(junk), ['Иванов Иван', 'Петров Пётр'], 'повтор шапки, «Итого» и номера пропускаются');
eq(junk.issues.length, 0, 'служебные строки не попадают в issues');
eq(junk.skipped, 4, 'пропущенные служебные строки посчитаны');

// ----------------------------------------------------------
// 7. Пустые и дублирующиеся строки
// ----------------------------------------------------------
var dupes = C.parseParticipants([
    ['ФИО', 'Гандикап'],
    ['Иванов Иван', '10'],
    ['', '10'],
    ['Иванов Иван', '11'],
    ['Иван', '11']
]);
eq(fios(dupes), ['Иванов Иван', 'Иван'], 'пустая строка и дубль ФИО пропускаются');
eq(dupes.issues.map(function (i) { return i.code; }), ['empty-name', 'duplicate'], 'issues: пустое имя и дубль');
eq(dupes.issues[0].row, 3, 'номер строки с пустым именем — как в файле');

// ----------------------------------------------------------
// 8. Все листы книги
// ----------------------------------------------------------
var book = C.parseWorkbook([
    { name: 'Состав', rows: [['Фамилия', 'Имя', 'Гандикап'], ['Иванов', 'Иван', '12,4']] },
    { name: 'Запас', rows: [['ФИО', 'ИГ'], ['Сидоров Пётр', '+2,5'], ['Иванов Иван', '12,4']] },
    { name: 'Пустой', rows: [] }
]);
eq(fios(book), ['Иванов Иван', 'Сидоров Пётр'], 'участники собираются со всех листов');
eq(his(book), [12.4, -2.5], 'гандикапы с разных листов');
eq(book.sheets.map(function (s) { return s.name + ':' + s.players; }), ['Состав:1', 'Запас:1'], 'статистика по листам');
eq(book.issues.length, 1, 'дубль между листами отмечен');
eq(book.issues[0].sheet, 'Запас', 'в проблеме указан лист');
eq(book.players[1].sheetName, 'Запас', 'у участника сохранено имя листа');

// ----------------------------------------------------------
// 9. Вставленный текст (TSV/CSV) и кавычки
// ----------------------------------------------------------
var pasted = C.parseParticipants(C.parseDelimited(
    'Фамилия\tИмя\tГандикап\nИванов\tИван\t12,4\nПетрова\tМария\t'
));
eq(fios(pasted), ['Иванов Иван', 'Петрова Мария'], 'вставленная таблица разбирается по табуляции');

var csv = C.parseParticipants(C.parseDelimited(
    'ФИО,Гандикап\n"Иванов, Иван",12,4\n"Петрова, Мария",'
));
eq(fios(csv), ['Иванов, Иван', 'Петрова, Мария'], 'CSV с кавычками и запятыми внутри ФИО');
eq(his(csv), [12.4, null], 'гандикап из CSV после кавычек');

// ----------------------------------------------------------
// 10. Участники готовы к добавлению в турнир
// ----------------------------------------------------------
var ready = C.parseParticipants([
    ['ФИО', 'Гандикап', 'Пол', 'ТИ', 'Группа'],
    ['Иванов Иван', '12,4', 'муж', 'Белый', 'A'],
    ['Смирнова Наталия', '24,2', 'жен', 'Красный', 'B']
]);
eq(ready.players[0].tee, 'wh', 'название ТИ «Белый» переведено в код wh');
eq(ready.players[1].tee, 'rd', '«Красный» → rd');
eq(ready.players[0].groupName, 'A', 'название группы из файла сохранено');
eq(ready.players[0].groupId, '', 'группа не подставляется как id (это делает админка)');
eq(ready.players[0].source, 'excel', 'источник участника — excel');
eq(C.hcpNumber('+2,5'), -2.5, 'плюсовой гандикап хранится отрицательным (как в АГР)');
eq(C.hcpNumber('—'), null, 'прочерк — это не гандикап');

console.log('\n' + (failures ? 'ПРОВАЛЕНО' : 'OK') + ': ' + total + ' проверок, ошибок: ' + failures);
process.exit(failures ? 1 : 0);
